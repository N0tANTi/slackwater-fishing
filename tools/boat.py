import math
from geometry import PaintedMesh, TAU, rng


def hull():
    m = PaintedMesh()
    stations = [
        (-1.74, 0.40, 0.08),
        (-1.55, 0.51, 0.035),
        (-1.2, 0.60, 0),
        (-0.65, 0.68, -0.013),
        (0, 0.70, -0.018),
        (0.55, 0.65, -0.002),
        (1.05, 0.51, 0.045),
        (1.45, 0.32, 0.13),
        (1.76, 0.10, 0.22),
        (1.83, 0.014, 0.27),
    ]
    colors = ["59392a", "834832", "b0663d", "bd6041", "e0b683", "ac4534"]
    levels = [
        (-0.24, 0.43),
        (-0.08, 0.68),
        (0.055, 0.82),
        (0.16, 0.90),
        (0.265, 0.96),
        (0.305, 0.98),
        (0.37, 1),
    ]
    for sign in (-1, 1):
        for (x, w, r), (nx, nw, nr) in zip(stations, stations[1:]):
            for j, ((height, width), (nh, nwidth)) in enumerate(zip(levels, levels[1:])):
                m.face(
                    [
                        (x, height + r, sign * w * width),
                        (nx, height + nr, sign * nw * width),
                        (nx, nh + nr, sign * nw * nwidth),
                        (x, nh + r, sign * w * nwidth),
                    ],
                    colors[j],
                )
            m.face(
                [
                    (x, 0.37 + r, sign * w),
                    (nx, 0.37 + nr, sign * nw),
                    (nx, 0.12 + nr, sign * (nw - 0.065)),
                    (x, 0.12 + r, sign * (w - 0.065)),
                ],
                "bc8651",
            )
            m.tube((x, 0.38 + r, sign * w), (nx, 0.38 + nr, sign * nw), 0.037, 0.037, "a74332")
            m.tube(
                (x, 0.21 + r, sign * w * 0.945),
                (nx, 0.21 + nr, sign * nw * 0.945),
                0.013,
                0.013,
                "e5ce9f",
                6,
            )
            if abs(x) < 1.5:
                m.tube(
                    (x, 0.03 + r, sign * w * 0.65),
                    (x, 0.345 + r, sign * (w - 0.04)),
                    0.031,
                    0.025,
                    "784c35",
                    5,
                )
        for x, w, r in stations[1:-1]:
            m.ball((x, 0.315 + r, sign * (w - 0.02)), (0.018, 0.016, 0.015), "d6a45e", 6, 3)
    m.box((-1.72, 0.14, 0), (0.08, 0.46, 0.76), "a45f3e")
    m.box((-1.74, 0.415, 0), (0.10, 0.075, 0.83), "9b4431")
    for a, b in zip(stations, stations[1:]):
        x, w, r = a
        nx, nw, nr = b
        for j in range(7):
            one = -1 + j * 2 / 7 + 0.012
            two = -1 + (j + 1) * 2 / 7 - 0.012
            m.face(
                [
                    (x, 0.076, w * 0.83 * one),
                    (x, 0.076, w * 0.83 * two),
                    (nx, 0.076, nw * 0.83 * two),
                    (nx, 0.076, nw * 0.83 * one),
                ],
                ["d7a260", "c68f53", "e2b77a", "bb8450", "d3a06b", "dca668", "c38d5b"][j],
            )
    for x, w in [(-1.23, 0.96), (-0.30, 1.19), (0.84, 0.93)]:
        for j in range(2):
            m.box((x + j * 0.137, 0.28, 0), (0.132, 0.083, w), "cea167" if j else "c28d59")
        for z in (-w * 0.41, w * 0.41):
            m.ball((x + 0.066, 0.326, z), (0.014, 0.008, 0.014), "604b3c", 6, 3)
    # Dark grain lines follow each board rather than crossing the join between floorboards.
    for col in range(7):
        for j in range(6):
            a = rng.uniform(-1.35, 0.79)
            z = (col - 3) * 0.12 + rng.uniform(-0.033, 0.033)
            length = rng.uniform(0.09, 0.28)
            m.path(
                [(a, 0.081, z), (a + length * 0.55, 0.081, z + 0.004), (a + length, 0.081, z + 0.001)],
                0.0028,
                "96734c",
                4,
            )
    for x, w in [(-1.23, 0.96), (-0.30, 1.19), (0.84, 0.93)]:
        for j in range(5):
            xx = x + rng.uniform(-0.05, 0.18)
            zz = rng.uniform(-0.38 * w, 0.10 * w)
            m.path(
                [(xx, 0.324, zz), (xx + 0.003, 0.324, zz + 0.11), (xx + 0.001, 0.324, zz + 0.24)],
                0.0022,
                "aa8051",
                4,
            )
    for sign in (-1, 1):
        m.tube((-0.46, 0.35, sign * 0.625), (-0.46, 0.44, sign * 0.625), 0.021, 0.017, "7d6e4d")
        m.path(
            [(-0.49, 0.45, sign * 0.625), (-0.46, 0.42, sign * 0.625), (-0.42, 0.46, sign * 0.625)],
            0.012,
            "b79e65",
            6,
        )
    # Hemp painter coiled at the bow and an old green creel behind the seat.
    for k in range(5):
        r = 0.065 + 0.017 * k
        m.path(
            [
                (1.19 + r * math.cos(i * TAU / 22), 0.16 + k * 0.004, r * 1.25 * math.sin(i * TAU / 22))
                for i in range(23)
            ],
            0.012,
            "d2ad73",
            5,
        )
    m.box((-0.87, 0.205, -0.22), (0.34, 0.24, 0.30), "626541")
    m.box((-0.87, 0.345, -0.22), (0.37, 0.045, 0.33), "b08d58")
    m.tube((1.62, 0.45, 0), (1.62, 0.84, 0), 0.023, 0.019, "684430")
    m.tube((1.61, 0.81, 0), (1.48, 0.81, 0), 0.018, 0.016, "684430")
    m.tube((1.49, 0.63, 0), (1.49, 0.76, 0), 0.052, 0.047, "ffcb6c")
    for y in (0.62, 0.77):
        m.tube((1.49, y, 0), (1.49, y + 0.025, 0), 0.065, 0.060, "6a4d32")
    m.save("skiff")


def fisher(pose):
    m = PaintedMesh()
    skin = "d89a67"
    coat = "e3ab42"
    pants = "3b597a"
    for side in (-1, 1):
        z = 0.13 * side
        m.tube((-0.2, 0.42, z), (0.13, 0.41, z * 1.35), 0.115, 0.103, pants)
        m.tube((0.12, 0.41, z * 1.35), (0.21, 0.17, z * 1.48), 0.105, 0.077, pants)
        m.ball((0.27, 0.145, z * 1.48), (0.14, 0.085, 0.083), "523b30")
    m.ball((-0.18, 0.60, 0), (0.235, 0.30, 0.235), coat, 13, 8)
    m.ball((-0.145, 0.60, 0.125), (0.197, 0.237, 0.112), "526e83", 11, 7)
    for x in (-0.24, -0.05):
        m.tube((x, 0.83, 0.115), (x + 0.025, 0.62, 0.213), 0.03, 0.038, "50657a", 6)
        m.ball((x + 0.025, 0.675, 0.218), (0.016, 0.017, 0.011), "dfb96b", 6, 3)
    m.tube((-0.15, 0.79, 0), (-0.13, 0.9, 0), 0.10, 0.085, skin)
    m.path(
        [(-0.25, 0.68, 0.211), (-0.21, 0.63, 0.234), (-0.145, 0.65, 0.23), (-0.13, 0.694, 0.223)],
        0.007,
        "80929a",
        5,
    )
    m.ball((-0.12, 0.978, 0.026), (0.183, 0.216, 0.169), skin, 16, 9)
    m.ball((-0.23, 1.025, -0.002), (0.119, 0.157, 0.153), "573c2f")
    for x in (-0.24, -0.17, -0.09, -0.01):
        m.ball((x, 1.106, 0.114), (0.052, 0.054, 0.048), "674832", 9, 5)
    for x in (-0.29, 0.044):
        m.ball((x, 0.974, 0.027), (0.042, 0.060, 0.043), skin, 10, 5)
    for x in (-0.201, -0.050):
        m.ball((x, 0.956, 0.167), (0.034, 0.017, 0.007), "d79066", 9, 4)
    for x in (-0.20, -0.05):
        m.ball((x, 1.008, 0.182), (0.020, 0.024, 0.010), "372d28", 9, 6)
        m.ball((x - 0.004, 1.014, 0.192), (0.005, 0.006, 0.003), "f5e5bf", 6, 3)
        m.path(
            [(x - 0.023, 1.046, 0.156), (x, 1.052, 0.162), (x + 0.018, 1.045, 0.166)], 0.006, "765039", 5
        )
    m.ball((-0.11, 0.964, 0.188), (0.035, 0.042, 0.034), "c78658")
    m.path([(-0.15, 0.913, 0.172), (-0.11, 0.902, 0.18), (-0.07, 0.916, 0.172)], 0.007, "764734")
    m.ball((-0.13, 1.183, -0.065), (0.347, 0.051, 0.317), "e6bb65", 30, 5)
    m.ball((-0.13, 1.239, -0.065), (0.202, 0.13, 0.195), "e0ad54", 24, 7)
    m.tube((-0.13, 1.202, -0.065), (-0.13, 1.236, -0.065), 0.202, 0.201, "a05935", 24)
    for i in range(3):
        r = 0.24 + 0.034 * i
        m.path(
            [
                (
                    -0.13 + r * math.cos(j * TAU / 34),
                    1.209 - 0.012 * i,
                    -0.065 + r * 0.91 * math.sin(j * TAU / 34),
                )
                for j in range(35)
            ],
            0.003,
            "bb8c48",
            4,
        )
    if pose == "hold":
        hands = [(0.09, 0.82, 0.29), (-0.40, 0.84, 0.27)]
    elif pose == "cast":
        hands = [(-0.06, 1.01, 0.30), (0.065, 0.88, 0.23)]
    else:
        hands = [(0.15, 0.71, 0.26), (0.09, 0.66, 0.17)]
    for (sx, sz), (hx, hy, hz) in zip([(-0.03, 0.12), (-0.32, 0.10)], hands):
        elbow = (sx + 0.04, (hy + 0.74) * 0.5 - 0.10, sz + 0.14)
        m.tube((sx, 0.76, sz), elbow, 0.096, 0.077, coat)
        m.tube(elbow, (hx, hy, hz), 0.067, 0.045, skin)
        m.ball((hx, hy, hz), (0.059, 0.058, 0.052), skin)
    m.save("fisher-" + pose)


